// Tests for src/lib/encrypt.js
//
// What we're checking:
//   - The happy path: encrypt then decrypt gives you back what you started with
//   - The v2 format records the iteration count and uses 600,000 iterations
//   - A real v1 ciphertext from the previous release still decrypts at 310,000
//   - The failure paths: wrong passphrase, tampered data, garbage input, and
//     unsupported versions all throw the right errors so the UI can show a
//     clear message
//   - The large-buffer fix from the changelog: a 1MB+ input doesn't blow the
//     call stack (the old spread-based implementation would have thrown a
//     RangeError here)
//
// Why no direct tests of bufferToBase64 / base64ToBuffer:
//   Those helpers are not exported from encrypt.js, they're internal
//   implementation details. We test them indirectly by using a large plaintext,
//   which forces both functions to process a big buffer. If they were broken,
//   the round-trip test would fail.

import { describe, it, expect } from "vitest";
import { encryptText, decryptText } from "@/lib/encrypt";

// Generated by encryptText() at the 1.0.0 code level, before the v2 change.
// It must remain readable forever, or every stored v1 ciphertext breaks.
const V1_FIXTURE =
  "sentinel:v1:lWa0NBZixP9+5Eu7cC0HUA==:UJ1R/17axcutQ3Qt:X0SytJvk8YFrTD5KXimEEcIEOmd1zCH0K649wMB5PtmccCgwii3mKxHQFEvxRw==";
const V1_FIXTURE_PASSPHRASE = "legacy-fixture-passphrase";
const V1_FIXTURE_PLAINTEXT = "Sentinel compatibility fixture";

// Replaces one colon-delimited field in a v2 string. Field indexes:
//   0 sentinel, 1 v2, 2 iterations, 3 salt, 4 iv, 5 ciphertext
function replaceV2Field(encrypted, index, value) {
  const parts = encrypted.split(":");
  parts[index] = value;
  return parts.join(":");
}

// ─── Round-trip ──────────────────────────────────────────────────────────────

describe("encryptText / decryptText round-trip", () => {
  it("decrypting with the same passphrase returns the original string", async () => {
    const original = "Hello, Sentinel!";
    const passphrase = "correct-horse-battery-staple";

    const encrypted = await encryptText(original, passphrase);
    const decrypted = await decryptText(encrypted, passphrase);

    expect(decrypted).toBe(original);
  });

  it("encrypted output uses v2 and records 600,000 iterations", async () => {
    // This doubles as a format regression test. Changing the prefix or the
    // iteration field without a deliberate version bump would be a bug.
    const encrypted = await encryptText("test", "pass");
    expect(encrypted.startsWith("sentinel:v2:600000:")).toBe(true);
  });

  it("two encryptions of the same plaintext produce different ciphertext", async () => {
    // AES-GCM uses a random salt and IV on every call. If this test ever
    // fails it means randomness was removed, which would be a serious
    // security regression: identical ciphertexts leak that two plaintexts
    // are the same.
    const a = await encryptText("same text", "same passphrase");
    const b = await encryptText("same text", "same passphrase");
    expect(a).not.toBe(b);
  });
});

// ─── Legacy v1 compatibility ─────────────────────────────────────────────────

describe("legacy v1 ciphertext", () => {
  it("still decrypts a ciphertext produced by the previous release", async () => {
    const decrypted = await decryptText(
      V1_FIXTURE,
      V1_FIXTURE_PASSPHRASE
    );
    expect(decrypted).toBe(V1_FIXTURE_PLAINTEXT);
  });

  it("throws DECRYPT_FAILED with the wrong passphrase", async () => {
    await expect(
      decryptText(V1_FIXTURE, "wrong-passphrase")
    ).rejects.toThrow("DECRYPT_FAILED");
  });

  it("honours the iteration count recorded in a v2 string", async () => {
    // Re-wrap the v1 fixture as v2 with an explicit 310,000 count. If the v2
    // parser ignored the count and always used 600,000, this would fail.
    const v1Payload = V1_FIXTURE.split(":").slice(2).join(":");
    const v2Wrapped = `sentinel:v2:310000:${v1Payload}`;

    const decrypted = await decryptText(
      v2Wrapped,
      V1_FIXTURE_PASSPHRASE
    );
    expect(decrypted).toBe(V1_FIXTURE_PLAINTEXT);
  });
});

// ─── Wrong passphrase ────────────────────────────────────────────────────────

describe("decryptText with a wrong passphrase", () => {
  it("throws an error with message DECRYPT_FAILED", async () => {
    const encrypted = await encryptText("secret", "correct-passphrase");

    // AES-GCM is an authenticated cipher: it detects that the key is wrong
    // and refuses to produce output, rather than decrypting to garbage.
    await expect(decryptText(encrypted, "wrong-passphrase")).rejects.toThrow(
      "DECRYPT_FAILED"
    );
  });
});

// ─── Tampered ciphertext ─────────────────────────────────────────────────────

describe("decryptText with tampered ciphertext", () => {
  it("throws DECRYPT_FAILED when one character in the ciphertext is changed", async () => {
    const encrypted = await encryptText("secret", "passphrase");

    // The ciphertext is the last colon-delimited segment. We flip one
    // character in it to simulate an attacker modifying the stored string.
    const parts = encrypted.split(":");
    const lastPart = parts[parts.length - 1];

    // Swap the first character for something different
    const tamperedChar = lastPart[0] === "A" ? "B" : "A";
    parts[parts.length - 1] = tamperedChar + lastPart.slice(1);
    const tampered = parts.join(":");

    // AES-GCM's authentication tag catches this. It uses the same error as a
    // wrong passphrase, deliberately, so attackers can't tell which failed.
    await expect(decryptText(tampered, "passphrase")).rejects.toThrow(
      "DECRYPT_FAILED"
    );
  });

  it("throws DECRYPT_FAILED if a different supported iteration count is substituted", async () => {
    const encrypted = await encryptText("secret", "passphrase");
    const tampered = replaceV2Field(encrypted, 2, "310000");

    // The count is not separate metadata. It feeds key derivation, so changing
    // it produces the wrong key and GCM authentication fails.
    await expect(decryptText(tampered, "passphrase")).rejects.toThrow(
      "DECRYPT_FAILED"
    );
  });
});

// ─── Malformed input ─────────────────────────────────────────────────────────

describe("decryptText with malformed input", () => {
  it("throws MALFORMED when the input isn't a Sentinel string", async () => {
    await expect(decryptText("not-a-sentinel-string", "pass")).rejects.toThrow(
      "MALFORMED"
    );
  });

  it("throws MALFORMED for an empty string", async () => {
    await expect(decryptText("", "pass")).rejects.toThrow("MALFORMED");
  });

  it("throws MALFORMED when a v2 payload has the wrong number of segments", async () => {
    await expect(
      decryptText("sentinel:v2:600000:onlytwoparts", "pass")
    ).rejects.toThrow("MALFORMED");
  });

  it("throws MALFORMED when a v1 payload has the wrong number of segments", async () => {
    await expect(
      decryptText("sentinel:v1:onlytwoparts:notthree", "pass")
    ).rejects.toThrow("MALFORMED");
  });

  it("throws MALFORMED when a base64 segment is invalid", async () => {
    await expect(
      decryptText("sentinel:v1:!!!:aGVsbG8=:d29ybGQ=", "pass")
    ).rejects.toThrow("MALFORMED");
  });

  it("throws MALFORMED when the iteration count is not a positive integer", async () => {
    const encrypted = await encryptText("secret", "passphrase");
    const malformed = replaceV2Field(encrypted, 2, "many");

    await expect(decryptText(malformed, "passphrase")).rejects.toThrow(
      "MALFORMED"
    );
  });

  it("throws MALFORMED when the iteration count is below the supported range", async () => {
    const encrypted = await encryptText("secret", "passphrase");
    const malformed = replaceV2Field(encrypted, 2, "1000");

    await expect(decryptText(malformed, "passphrase")).rejects.toThrow(
      "MALFORMED"
    );
  });

  it("throws MALFORMED when the iteration count is above the supported range", async () => {
    const encrypted = await encryptText("secret", "passphrase");
    const malformed = replaceV2Field(encrypted, 2, "999999999");

    await expect(decryptText(malformed, "passphrase")).rejects.toThrow(
      "MALFORMED"
    );
  });

  it("throws MALFORMED when the salt has the wrong length", async () => {
    const encrypted = await encryptText("secret", "passphrase");
    const malformed = replaceV2Field(encrypted, 3, "AAAA");

    await expect(decryptText(malformed, "passphrase")).rejects.toThrow(
      "MALFORMED"
    );
  });

  it("throws MALFORMED when the IV has the wrong length", async () => {
    const encrypted = await encryptText("secret", "passphrase");
    const malformed = replaceV2Field(encrypted, 4, "AAAA");

    await expect(decryptText(malformed, "passphrase")).rejects.toThrow(
      "MALFORMED"
    );
  });

  it("throws MALFORMED when the ciphertext is shorter than the GCM tag", async () => {
    const encrypted = await encryptText("secret", "passphrase");
    const malformed = replaceV2Field(encrypted, 5, "AAAA");

    await expect(decryptText(malformed, "passphrase")).rejects.toThrow(
      "MALFORMED"
    );
  });

  it("throws UNSUPPORTED_VERSION for a newer format", async () => {
    await expect(
      decryptText("sentinel:v3:600000:a:b:c", "pass")
    ).rejects.toThrow("UNSUPPORTED_VERSION");
  });

  it("throws MALFORMED when the version is empty", async () => {
    await expect(
      decryptText("sentinel::600000:a:b:c", "pass")
    ).rejects.toThrow("MALFORMED");
  });
});

// ─── Large buffer (stack-overflow regression) ────────────────────────────────

describe("large buffer handling", () => {
  it("round-trips a 1MB+ plaintext without throwing a RangeError", async () => {
    // The old spread-based bufferToBase64 used String.fromCharCode(...array),
    // which passes every byte as a separate function argument. JS engines
    // have a call-stack argument limit (typically ~65,000-125,000). A 1MB
    // buffer is ~1,000,000 bytes, which blows that limit and throws:
    //   RangeError: Maximum call stack size exceeded
    //
    // The fixed version uses a for...of loop, which has no such limit.
    // This test catches any regression back to the spread pattern.
    const oneMegabyte = "x".repeat(1024 * 1024); // 1,048,576 characters
    const passphrase = "large-buffer-test";

    const encrypted = await encryptText(oneMegabyte, passphrase);
    const decrypted = await decryptText(encrypted, passphrase);

    expect(decrypted).toBe(oneMegabyte);
  }, 30_000); // 30s timeout, PBKDF2 at 600k iterations is intentionally slow
});
